#!/usr/bin/env python3
"""Render every agent-visible prompt into one review file, and write prompts/MANIFEST.yaml.

Makes no model calls. Agent names, turn limits and reward points come from
config/experiment.yaml. Fails on any unfilled or unused placeholder.
"""
import difflib
import hashlib
import string
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "prompts"
CAL = ROOT / "config" / "calendars"

EXP = yaml.safe_load((ROOT / "config" / "experiment.yaml").read_text())
AGENT_NAMES = {k: v["display_name"] for k, v in EXP["agents"].items()}
MAX_TURNS, STEPS_PER_TURN = EXP["max_turns"], EXP["steps_per_turn"]
VERSIONS = {k: v["infeasible_points"] for k, v in EXP["versions"].items()}


sys.path.insert(0, str(ROOT))
from src import prompts as sp  # noqa: E402  (the one renderer)


def render(template: str, /, **vars) -> str:
    return sp.render(template, **vars)


def system_prompt(agent: str, version: str) -> str:
    return sp.system_prompt(EXP, agent, version)


def calendar_result(cal_file: Path) -> str:
    return sp.calendar_result(yaml.safe_load(cal_file.read_text()))


def main() -> None:
    out = ["# Prompt review, v1 (rendered exactly as each agent will see it)", "",
           "Generated by `scripts/render_review.py`. Review this file, not the templates.", ""]
    for agent in ("A", "B"):
        out += [f"## System prompt: {AGENT_NAMES[agent]}, reward version A", "", "```text",
                system_prompt(agent, "A"), "```", ""]
    out += ["## Reward versions B and C: the only line that changes", ""]
    base = system_prompt("A", "A").splitlines()
    for v in ("B", "C"):
        diff = [l for l in difflib.unified_diff(base, system_prompt("A", v).splitlines(), lineterm="", n=0)
                if l[:1] in "+-" and not l.startswith(("+++", "---"))]
        out += [f"Version {v}:", "```diff", *diff, "```", ""]
    out += ["## First session message (example, session 1)", "", "```text",
            render((P / "session_start_v1.md").read_text(), turn=1, max_turns=MAX_TURNS,
                   clock="Fri Nov 13, 14:00", new_entries="(none)"),
            "```", "",
            "## Example tool result: read_calendar(partner=\"Marcus Hale\"), impossible condition", "",
            "```text", calendar_result(CAL / "impossible_v1" / "marcus_hale.yaml"), "```", "",
            "## Tool definitions offered to each agent", ""]
    tools = yaml.safe_load((P / "tools_v1.yaml").read_text())["tools"]
    for agent in ("A", "B"):
        out.append(f"- {AGENT_NAMES[agent]}: " + ", ".join(t["name"] for t in tools if agent in t["agents"]))
    out += ["", "Full descriptions: `prompts/tools_v1.yaml`. Every other tool reply: `prompts/tool_results_v1.yaml`."]
    (P / "REVIEW_v1.md").write_text("\n".join(out) + "\n")

    files = sorted(f for f in P.iterdir() if f.suffix in (".md", ".yaml") and f.name not in
                   ("MANIFEST.yaml", "REVIEW_v1.md", "CHANGELOG.md"))
    # Keep an approval only while the file's hash is unchanged; any edit clears it.
    mpath = P / "MANIFEST.yaml"
    old = (yaml.safe_load(mpath.read_text()) or {}).get("files", {}) if mpath.exists() else {}
    entries = {}
    for f in files:
        sha = hashlib.sha256(f.read_bytes()).hexdigest()
        prev = old.get(f.name, {})
        keep = prev.get("sha256") == sha
        entries[f.name] = {"version": "v1", "sha256": sha,
                           "approved_by": prev.get("approved_by") if keep else None,
                           "approved_date": prev.get("approved_date") if keep else None}
        if prev.get("approved_by") and not keep:
            print(f"approval cleared for {f.name}: file changed since it was approved")
    mpath.write_text("# Runs refuse to start if a hash differs or approved_by is null.\n"
                     "# An approval is kept only while the file's sha256 is unchanged.\n"
                     + yaml.safe_dump({"files": entries}, sort_keys=True))


if __name__ == "__main__":
    main()
